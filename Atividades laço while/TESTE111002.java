public class TESTE111002 {
    public static void main (String[] args) {

        int numero = 10;
        double metade;

        while (numero <= 20) {
            metade = numero / 2.0;
            System.out.println("A metade de: " + numero + " é " + metade);
            numero++;
        }
    }

}
